/**
 * Writes migration 1136 (the cutting machines' spindle speed limits) from memory/:
 *   node scripts/generate-machining-spindle-limits-migration.js
 *
 * A machining line's spindle speed is n = 1000 x cutting speed / (pi x diameter) (the workbook memory/Machining - Calculator
 * Database (1).xlsx, every cutting sheet). On a small diameter that n passes what the machine can turn: 7,118 rpm was computed for a
 * Haas DS-30Y (4,000 rpm). The machine's own limit is in memory/machining/machine/*.csv (limits.spindleSpeedRpm, and
 * rates.liveToolingSpindleSpeedRpm for a lathe's driven tools) but was never staged on mhr_records, so calculators carried a
 * 10,000 rpm default instead. Written by machine class and name to every location's rows, as specs keys:
 *   spindle_speed_rpm        the main spindle's top speed
 *   live_tooling_speed_rpm   the driven-tool spindle's top speed (lathes and mill-turns that have one)
 * The multi-spindle machines already carry both (migration 1093).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1136_machining_spindle_limits.sql');

// Each source CSV, its name / class / limit columns. `classOf` maps the CSV's machine type to the HR Rates machine_class.
const SOURCES = [
  {
    file: 'machining/machine/machiningusa.csv', name: 'name', spindle: 'limits.spindleSpeedRpm', live: 'rates.liveToolingSpindleSpeedRpm',
    classOf: (r) => ({
      '2 Axis Lathe': '2_axis_lathe', '3 Axis Lathe': '3_axis_lathe',
      '2 Axis Bar Feed Lathe with Sub Spindle': '2_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Bar Feed Lathe with Sub Spindle': '3_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Mill': '3_axis_mill', '4 Axis Mill': '4_axis_mill', '5 Axis Mill': '5_axis_mill',
      '3 Axis Router': '3_axis_router', '5 Axis Router': '5_axis_router',
    })[String(r.primaryId).trim()] ?? null,
  },
  { file: 'machining/machine/millturn_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', live: 'rates.live_tooling_spindle_speed_rpm', classOf: () => 'machining_millturn' },
  { file: 'machining/machine/stock_prep_lathe_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', classOf: () => 'stock_prep_lathe' },
  { file: 'machining/machine/stock_prep_mill_work_center_data.csv', name: 'primary_id.name', spindle: 'spindle_speed_rpm', classOf: () => 'stock_prep_mill' },
  { file: 'machining/machine/drill_press_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', classOf: () => 'drill_press' },
  { file: 'machining/machine/jig_bore_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', classOf: () => 'jig_bore' },
  { file: 'machining/machine/deep_bore_machine_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', classOf: () => 'deep_bore_machine' },
  { file: 'machining/machine/gun_drill_usa.csv', name: 'name', spindle: 'limits.spindle_speed_rpm', classOf: () => 'gun_drill' },
];

const q = (s) => `$str$${s}$str$`;
const rpm = (v, what) => {
  const s = String(v ?? '').trim();
  if (s === '') return null;
  const n = Number(s);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`${what}: not a speed "${v}"`);
  return n;
};

const machines = new Map();
for (const src of SOURCES) {
  for (const r of readCsv(join(MEMORY, src.file)).rows) {
    const machineClass = src.classOf(r);
    if (!machineClass) continue; // bench cells, deburr cells and bevel gear cutters: not cutting machines a calculator times
    const name = String(r[src.name]).trim();
    const spindleSpeedRpm = rpm(r[src.spindle], `${src.file} ${name}`);
    if (spindleSpeedRpm == null) throw new Error(`${src.file}: ${name} has no spindle speed`);
    const liveToolingSpeedRpm = src.live ? rpm(r[src.live], `${src.file} ${name} live tooling`) : null;
    const key = `${machineClass}\u0000${name}`;
    if (machines.has(key)) throw new Error(`${machineClass} ${name} listed twice`);
    machines.set(key, { machineClass, name, spindleSpeedRpm, liveToolingSpeedRpm });
  }
}
const rows = [...machines.values()].sort((a, b) => a.machineClass.localeCompare(b.machineClass) || a.name.localeCompare(b.name));
const classes = [...new Set(rows.map((m) => m.machineClass))].sort();

const row = (m) => `  (${[q(m.machineClass), q(m.name), m.spindleSpeedRpm, m.liveToolingSpeedRpm ?? 'NULL::numeric'].join(', ')})`;
const classList = classes.map((c) => `'${c}'`).join(', ');

const sql = `-- ============================================================================
-- Migration 1136: the cutting machines' spindle speed limits
-- ============================================================================
-- Generated by scripts/generate-machining-spindle-limits-migration.js; re-run it and diff instead of editing.
--
-- A machining line's spindle speed is n = 1000 x cutting speed / (pi x diameter) (memory/Machining - Calculator Database (1).xlsx,
-- every cutting sheet). On a small diameter that passes what the machine can turn (7,118 rpm was computed for a 4,000 rpm Haas
-- DS-30Y), so the calculators cap it at the machine's limit. The limits are the machine reference data's own
-- (memory/machining/machine/*.csv: limits.spindleSpeedRpm, rates.liveToolingSpindleSpeedRpm) and were never staged on mhr_records;
-- calculators carried a 10,000 rpm default instead.
--
-- Written by machine class and name to every location's rows, as specs keys:
--   spindle_speed_rpm        the main spindle's top speed
--   live_tooling_speed_rpm   the driven-tool spindle's top speed (only machines that have one)
-- ${rows.length} machines in ${classes.length} classes. The multi-spindle machines carry both already (migration 1093).
--
-- Idempotent: the same values are re-set.
-- Verify: SELECT machine_class, location, count(*), count(specs->'spindle_speed_rpm') FROM mhr_records
--           WHERE machine_class IN (${classList}) GROUP BY 1, 2 ORDER BY 1, 2;
-- ============================================================================

UPDATE mhr_records m SET
  specs = COALESCE(m.specs, '{}'::jsonb) - 'live_tooling_speed_rpm'
    || jsonb_build_object('spindle_speed_rpm', v.spindle_speed_rpm)
    || CASE WHEN v.live_tooling_speed_rpm IS NULL THEN '{}'::jsonb
            ELSE jsonb_build_object('live_tooling_speed_rpm', v.live_tooling_speed_rpm) END,
  updated_at = now()
FROM (VALUES
${rows.map(row).join(',\n')}
) AS v(machine_class, machine_name, spindle_speed_rpm, live_tooling_speed_rpm)
WHERE m.machine_class = v.machine_class AND m.machine_name = v.machine_name;

DO $spindle_check$
DECLARE bare text[];
BEGIN
  SELECT array_agg(location || ': ' || machine_class || ' ' || machine_name ORDER BY location, machine_class, machine_name) INTO bare
    FROM mhr_records
   WHERE machine_class IN (${classList}) AND NOT COALESCE(specs, '{}'::jsonb) ? 'spindle_speed_rpm';
  IF bare IS NOT NULL THEN RAISE EXCEPTION 'Cutting machines still without a spindle speed limit (not in memory/machining/machine): %', bare; END IF;
END $spindle_check$;

NOTIFY pgrst, 'reload schema';
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} machines, ${classes.length} classes)`);
