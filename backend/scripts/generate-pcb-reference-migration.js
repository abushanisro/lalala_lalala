/**
 * Writes migration 1130 (the sourced PCB fabrication reference: consumables, process times and yields) from memory/PCBA:
 *   node scripts/generate-pcb-reference-migration.js
 * Each file is staged whole as a lookup table of source version 2026-PCB, beside the stack-up tables migration 823 staged, so the PCB
 * engine reads it with the rest of the reference. Every row keeps its source (source_url, source_date, source_note).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1130_pcb_sourced_reference.sql');
const SOURCE_VERSION = '2026-PCB';

const TABLES = [
  { name: 'consumables', file: 'PCBA/consumables.csv', what: 'consumables and tooling: prepreg, solder mask, dry film, plating metals and their densities, drill and router bits and their life, entry and backup boards, test fixtures, the stamping die' },
  { name: 'process_times', file: 'PCBA/process_times.csv', what: 'process times and thicknesses: etch-resist tin, ENIG nickel and gold, HASL dwell, the dryer\'s heated length, the working panel, the solder mask solids' },
  { name: 'yield', file: 'PCBA/yield.csv', what: 'first-pass fabrication yield by layer count' },
];

const q = (s) => `$str$${s}$str$`;
const staged = TABLES.map((t) => {
  const { columns, rows } = readCsv(join(MEMORY, t.file));
  for (const c of ['item_key', 'source_url', 'source_date']) if (!columns.includes(c)) throw new Error(`${t.file}: no ${c} column`);
  for (const r of rows) {
    if (!/^https?:\/\//.test(String(r.source_url ?? ''))) throw new Error(`${t.file}: a row without a source_url (${JSON.stringify(r).slice(0, 120)})`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(r.source_date ?? ''))) throw new Error(`${t.file}: a row without an ISO source_date`);
  }
  const keyed = rows.filter((r) => r.item_key).length;
  const raw = { table_name: t.name, source_files: [t.file], status: 'COMPLETE', columns, rows };
  return { ...t, rows: rows.length, keyed, raw };
});

const sql = `-- ============================================================================
-- Migration 1130: the sourced PCB fabrication reference (consumables, process times, yields)
-- ============================================================================
-- Generated by scripts/generate-pcb-reference-migration.js; re-run it and diff instead of editing.
--
-- memory/PCBA states the machines, the stack-up tables and the process variables of bare-board fabrication, but not what the boards
-- consume, some process times and no yield. These were researched and sourced (user decision 2026-11-23: every row carries its
-- source_url, source_date and source_note; ranges are min and max columns, quoted at their midpoint with both ends shown). memory's own
-- values win wherever it states one: these rows only fill what it leaves out. The rows the engine reads carry an item_key; the others are
-- kept for review.
--
-- Staged whole as lookup tables of source version ${SOURCE_VERSION} (beside migration 823's stack-up tables):
${staged.map((t) => `--   ${t.name.padEnd(14)}${String(t.rows).padStart(4)} rows (${t.keyed} keyed)  memory/${t.file}: ${t.what}`).join('\n')}
--
-- Idempotent: a table already staged is left as it is (a changed file ships as a new migration).
-- Verify: SELECT key, value FROM machining_reference_data WHERE source_version = '${SOURCE_VERSION}' AND category = 'lookup_table' ORDER BY 1;
-- ============================================================================

INSERT INTO machining_reference_data (category, source_region, source_version, key, value, unit_type, notes, raw) VALUES
${staged.map((t) => `  ($str$lookup_table$str$, 'USA', ${q(SOURCE_VERSION)}, ${q(t.name)}, ${q(String(t.rows))}, NULL, ${q(`Staged from memory/${t.file} (researched, sourced: user decision 2026-11-23)`)}, $jsonb$${JSON.stringify(t.raw)}$jsonb$::jsonb)`).join(',\n')}
ON CONFLICT (category, source_region, source_version, key) DO NOTHING;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${staged.map((t) => `${t.name} ${t.rows}`).join(', ')})`);
