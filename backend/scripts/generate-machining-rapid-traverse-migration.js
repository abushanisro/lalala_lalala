/**
 * Writes migration 1141 (the cutting machines' rapid traverse rates) from memory/:
 *   node scripts/generate-machining-rapid-traverse-migration.js
 *
 * A mill moves between the features it cuts at its rapid traverse rate. The milling line carried a flat 15 % "rapids and tool change"
 * allowance on its cutting time instead; the project owner's decision of 2026-11-24 replaces it with the rapids from data: each move is
 * the machining variables' rapidTransferDistanceFactor (0.5) x the part's box length, at the machine's own rapid traverse rate. The rate
 * is in memory/machining/machine/*.csv (rates.rapidTraverseRateMmPerMin and its spellings) but was never staged on mhr_records. Written
 * by machine class and name to every location's rows, as the specs key rapid_traverse_mm_per_min, for the machines migration 1136 gave
 * a spindle limit (the same sources).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1141_machining_rapid_traverse_rates.sql');

// Each source CSV, its name / class / rapid traverse columns. `classOf` maps the CSV's machine type to the HR Rates machine_class.
const SOURCES = [
  {
    file: 'machining/machine/machiningusa.csv', name: 'name', rapid: 'rates.rapidTraverseRateMmPerMin',
    classOf: (r) => ({
      '2 Axis Lathe': '2_axis_lathe', '3 Axis Lathe': '3_axis_lathe',
      '2 Axis Bar Feed Lathe with Sub Spindle': '2_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Bar Feed Lathe with Sub Spindle': '3_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Mill': '3_axis_mill', '4 Axis Mill': '4_axis_mill', '5 Axis Mill': '5_axis_mill',
      '3 Axis Router': '3_axis_router', '5 Axis Router': '5_axis_router',
    })[String(r.primaryId).trim()] ?? null,
  },
  { file: 'machining/machine/millturn_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'machining_millturn' },
  { file: 'machining/machine/stock_prep_lathe_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'stock_prep_lathe' },
  { file: 'machining/machine/stock_prep_mill_work_center_data.csv', name: 'primary_id.name', rapid: 'rates.rapid_traverse_rate_mm_min', classOf: () => 'stock_prep_mill' },
  { file: 'machining/machine/drill_press_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'drill_press' },
  { file: 'machining/machine/jig_bore_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'jig_bore' },
  { file: 'machining/machine/deep_bore_machine_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'deep_bore_machine' },
  { file: 'machining/machine/gun_drill_usa.csv', name: 'name', rapid: 'rates.rapid_traverse_rate_mm_per_min', classOf: () => 'gun_drill' },
];

const q = (s) => `$str$${s}$str$`;
const rate = (v, what) => {
  const n = Number(String(v ?? '').trim());
  if (!Number.isFinite(n) || n <= 0) throw new Error(`${what}: not a rapid traverse rate "${v}"`);
  return n;
};

const machines = new Map();
for (const src of SOURCES) {
  for (const r of readCsv(join(MEMORY, src.file)).rows) {
    const machineClass = src.classOf(r);
    if (!machineClass) continue; // bench cells, deburr cells and bevel gear cutters: not cutting machines a calculator times
    const name = String(r[src.name]).trim();
    const key = `${machineClass}\u0000${name}`;
    if (machines.has(key)) throw new Error(`${machineClass} ${name} listed twice`);
    machines.set(key, { machineClass, name, rapidMmPerMin: rate(r[src.rapid], `${src.file} ${name}`) });
  }
}
const rows = [...machines.values()].sort((a, b) => a.machineClass.localeCompare(b.machineClass) || a.name.localeCompare(b.name));
const classes = [...new Set(rows.map((m) => m.machineClass))].sort();
const classList = classes.map((c) => `'${c}'`).join(', ');

const sql = `-- ============================================================================
-- Migration 1141: the cutting machines' rapid traverse rates
-- ============================================================================
-- Generated by scripts/generate-machining-rapid-traverse-migration.js; re-run it and diff instead of editing.
--
-- A mill moves between the features it cuts at its rapid traverse rate. The milling line carried a flat 15 % allowance for rapids
-- and tool changes on its cutting time instead; the project owner's decision of 2026-11-24 replaces it with the rapids from data: each
-- move is the machining variables' rapidTransferDistanceFactor (0.5) x the part's box length, at the machine's own rapid traverse rate
-- (memory/machining/machine/*.csv: rates.rapidTraverseRateMmPerMin and its spellings), which was never staged on mhr_records.
--
-- Written by machine class and name to every location's rows, as the specs key:
--   rapid_traverse_mm_per_min   the machine's rapid traverse rate (mm/min)
-- ${rows.length} machines in ${classes.length} classes: the machines migration 1136 gave a spindle limit.
--
-- Idempotent: the same values are re-set.
-- Verify: SELECT machine_class, location, count(*), count(specs->'rapid_traverse_mm_per_min') FROM mhr_records
--           WHERE machine_class IN (${classList}) GROUP BY 1, 2 ORDER BY 1, 2;
-- ============================================================================

UPDATE mhr_records m SET
  specs = COALESCE(m.specs, '{}'::jsonb) || jsonb_build_object('rapid_traverse_mm_per_min', v.rapid_traverse_mm_per_min),
  updated_at = now()
FROM (VALUES
${rows.map((m) => `  (${[q(m.machineClass), q(m.name), m.rapidMmPerMin].join(', ')})`).join(',\n')}
) AS v(machine_class, machine_name, rapid_traverse_mm_per_min)
WHERE m.machine_class = v.machine_class AND m.machine_name = v.machine_name;

DO $rapid_check$
DECLARE bare text[];
BEGIN
  SELECT array_agg(location || ': ' || machine_class || ' ' || machine_name ORDER BY location, machine_class, machine_name) INTO bare
    FROM mhr_records
   WHERE machine_class IN (${classList}) AND NOT COALESCE(specs, '{}'::jsonb) ? 'rapid_traverse_mm_per_min';
  IF bare IS NOT NULL THEN RAISE EXCEPTION 'Cutting machines still without a rapid traverse rate (not in memory/machining/machine): %', bare; END IF;
END $rapid_check$;

NOTIFY pgrst, 'reload schema';
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} machines, ${classes.length} classes)`);
