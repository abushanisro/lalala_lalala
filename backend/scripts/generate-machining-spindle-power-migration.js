/**
 * Writes migration 1165 (the cutting machines' spindle power) from memory/:
 *   node scripts/generate-machining-spindle-power-migration.js
 *
 * The machining variables choose a machine by its spindle: spindlePowerBias and spindleSpeedBias, "For machine selection, 0 to 1. 0
 * selects the cheapest hourly machine. 0.5 selects only machines more powerful / faster than the average." A machine's top spindle speed is
 * staged (migration 1136); its spindle power is in the same machine files (powers.spindlePowerKw and its spellings) but was never staged on
 * mhr_records, so the power bias had nothing to compare. Written by machine class and name to every location's rows, as a specs key:
 *   spindle_power_kw   the main spindle's power
 * It is the spindle's own power, not the machine's connected load (machine_power_kw), and it is kept out of the capability column power_kw.
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1165_machining_spindle_power.sql');

// Each source CSV and the machine class of its rows: the cutting machines migration 1136 gave a spindle speed.
const machining = (file, machineClass) => ({ file: `Machining/machine/${file}`, classOf: () => machineClass });
const SOURCES = [
  {
    file: 'Machining/machine/machiningusa.csv',
    classOf: (r) => ({
      '2 Axis Lathe': '2_axis_lathe', '3 Axis Lathe': '3_axis_lathe',
      '2 Axis Bar Feed Lathe with Sub Spindle': '2_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Bar Feed Lathe with Sub Spindle': '3_axis_bar_feed_lathe_with_sub_spindle',
      '3 Axis Mill': '3_axis_mill', '4 Axis Mill': '4_axis_mill', '5 Axis Mill': '5_axis_mill',
      '3 Axis Router': '3_axis_router', '5 Axis Router': '5_axis_router',
    })[String(r.primaryId).trim()] ?? null,
  },
  machining('millturn_usa.csv', 'machining_millturn'),
  machining('stock_prep_lathe_usa.csv', 'stock_prep_lathe'),
  machining('stock_prep_mill_work_center_data.csv', 'stock_prep_mill'),
  machining('drill_press_usa.csv', 'drill_press'),
  machining('jig_bore_usa.csv', 'jig_bore'),
  machining('deep_bore_machine_usa.csv', 'deep_bore_machine'),
  machining('gun_drill_usa.csv', 'gun_drill'),
];

const NAME_COLUMNS = ['name', 'primary_id.name'];
// The main spindle's power, in any of the files' spellings; never the live tooling spindle's.
const SPINDLE_POWER = /(^|\.)spindle_?power_?kw$/i;

const q = (s) => `$str$${s}$str$`;

const machines = new Map();
for (const src of SOURCES) {
  const { rows } = readCsv(join(MEMORY, src.file));
  const columns = Object.keys(rows[0] ?? {});
  const nameColumn = NAME_COLUMNS.find((c) => columns.includes(c));
  const powerColumn = columns.find((c) => SPINDLE_POWER.test(c) && !/live/i.test(c));
  if (!nameColumn || !powerColumn) throw new Error(`${src.file}: no name or spindle power column (${columns.slice(0, 8).join(', ')}, ...)`);
  for (const r of rows) {
    const machineClass = src.classOf(r);
    if (!machineClass) continue; // bench cells, deburr cells and bevel gear cutters: no cutting spindle a calculator times
    const name = String(r[nameColumn]).trim();
    const text = String(r[powerColumn] ?? '').trim();
    if (text === '') continue; // the file gives no spindle power for this machine: no key
    const kw = Number(text);
    if (!Number.isFinite(kw) || kw <= 0) throw new Error(`${src.file} ${name}: not a spindle power "${r[powerColumn]}"`);
    const key = `${machineClass}\u0000${name}`;
    if (machines.has(key)) throw new Error(`${machineClass} ${name} listed twice`);
    machines.set(key, { machineClass, name, kw });
  }
}
const list = [...machines.values()].sort((a, b) => a.machineClass.localeCompare(b.machineClass) || a.name.localeCompare(b.name));
const classes = [...new Set(list.map((m) => m.machineClass))].sort();
const row = (m) => `  (${[q(m.machineClass), q(m.name), m.kw].join(', ')})`;

const sql = `-- ============================================================================
-- Migration 1165: the cutting machines' spindle power
-- ============================================================================
-- Generated by scripts/generate-machining-spindle-power-migration.js; re-run it and diff instead of editing.
--
-- The machining variables choose a machine by its spindle: spindlePowerBias and spindleSpeedBias, "For machine selection, 0 to 1.
-- 0 selects the cheapest hourly machine. 0.5 selects only machines more powerful / faster than the average." Each machine's top
-- spindle speed is staged (migration 1136); its spindle power is in the same machine files (memory/Machining/machine/*.csv:
-- powers.spindlePowerKw and its spellings) but was never staged on mhr_records, so the power bias had nothing to compare.
--
-- Written by machine class and name to every location's rows, as a specs key:
--   spindle_power_kw   the main spindle's power (kW)
-- ${list.length} machines in ${classes.length} classes. It is the spindle's own power, not the machine's connected load
-- (machine_power_kw), and it is kept out of the capability column power_kw.
--
-- Idempotent: the same values are re-set.
-- Verify: SELECT machine_class, location, count(*), count(specs->'spindle_power_kw') FROM mhr_records
--           WHERE machine_class IN (${classes.map((c) => `'${c}'`).join(', ')}) GROUP BY 1, 2 ORDER BY 1, 2;
-- ============================================================================

UPDATE mhr_records m SET
  specs = COALESCE(m.specs, '{}'::jsonb) || jsonb_build_object('spindle_power_kw', v.spindle_power_kw),
  updated_at = now()
FROM (VALUES
${list.map(row).join(',\n')}
) AS v(machine_class, machine_name, spindle_power_kw)
WHERE m.machine_class = v.machine_class AND m.machine_name = v.machine_name;

NOTIFY pgrst, 'reload schema';
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${list.length} machines, ${classes.length} classes)`);
